"""
Static blog builder for porterjenkins.com.

Usage
-----
  uv run blog.py build              # render every post in posts/ into blog/
  uv run blog.py build --drafts     # include posts marked `draft: true`
  uv run blog.py import PATH.md     # copy an external markdown file (and its
                                    # local images) into posts/<slug>/ and build
  uv run blog.py import PATH.md --slug my-slug
  uv run blog.py serve              # build, then preview at http://127.0.0.1:8000/blog/

(`python3 blog.py ...` also works if the dependencies above are installed,
e.g. `pip install -r requirements.txt`.)

Post layout
-----------
  posts/<slug>/index.md     markdown with a front-matter block
  posts/<slug>/figure.png   any sibling files are copied next to the page
  posts/<slug>.md           single-file posts are fine too

Front matter (all keys optional except title):
  ---
  title: A title
  date: 2026-10-12
  summary: One or two sentences shown on listing cards.
  tags: ml, uncertainty
  draft: true
  ---

Markdown features: GitHub-style tables, fenced code with syntax highlighting,
footnotes, definition lists, heading anchors, LaTeX via $...$ / $$...$$
(rendered client-side by KaTeX), and images that become <figure> blocks with
the alt text (or title) as the caption.
"""
from __future__ import annotations

import argparse
import datetime as dt
import html
import re
import shutil
import sys
import xml.etree.ElementTree as etree
from dataclasses import dataclass, field
from pathlib import Path

import markdown
from markdown.extensions import Extension
from markdown.treeprocessors import Treeprocessor

ROOT = Path(__file__).resolve().parent
POSTS_DIR = ROOT / "posts"
OUT_DIR = ROOT / "blog"
TEMPLATES_DIR = ROOT / "templates"
HOME_HTML = ROOT / "index.html"

SITE_NAME = "Porter Jenkins"
SITE_URL = "https://porterjenkins.com"
HOME_CARD_COUNT = 3
WORDS_PER_MINUTE = 220
GENERATED_MARK = "<!-- generated by blog.py; edit posts/ and rebuild -->"
HOME_START = "<!-- BLOG:START -->"
HOME_END = "<!-- BLOG:END -->"

# ----------------------------------------------------------------------------
# Markdown extensions
# ----------------------------------------------------------------------------


class FigureProcessor(Treeprocessor):
    """Turn a paragraph that contains only an image into <figure> + <figcaption>."""

    def run(self, root):
        for parent in list(root.iter()):
            for i, child in enumerate(list(parent)):
                if not self._is_lone_image(child):
                    continue
                img = child[0]
                fig = etree.Element("figure")
                img.tail = None
                img.set("loading", "lazy")
                caption = img.get("title") or img.get("alt") or ""
                if img.get("title") is not None:
                    del img.attrib["title"]
                fig.append(img)
                if caption.strip():
                    cap = etree.SubElement(fig, "figcaption")
                    cap.text = caption
                fig.tail = child.tail
                parent.remove(child)
                parent.insert(i, fig)

    @staticmethod
    def _is_lone_image(el) -> bool:
        return (
            el.tag == "p"
            and len(el) == 1
            and el[0].tag == "img"
            and not (el.text or "").strip()
            and not (el[0].tail or "").strip()
        )


class FigureExtension(Extension):
    def extendMarkdown(self, md):
        md.treeprocessors.register(FigureProcessor(md), "figure", 5)


def make_markdown() -> markdown.Markdown:
    return markdown.Markdown(
        extensions=[
            "tables",
            "attr_list",
            "md_in_html",
            "footnotes",
            "def_list",
            "abbr",
            "toc",
            "pymdownx.arithmatex",
            "pymdownx.superfences",
            "pymdownx.highlight",
            "pymdownx.inlinehilite",
            "pymdownx.betterem",
            FigureExtension(),
        ],
        extension_configs={
            "pymdownx.arithmatex": {"generic": True},
            "pymdownx.highlight": {
                "css_class": "highlight",
                "guess_lang": False,
                "linenums": False,
            },
            "toc": {
                "permalink": "#",
                "permalink_title": "Link to this section",
                "toc_depth": "2-3",
            },
        },
        output_format="html5",
    )


