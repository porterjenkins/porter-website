# Import
# ----------------------------------------------------------------------------

MD_IMAGE_RE = re.compile(r"(!\[[^\]]*\]\()([^)\s]+)((?:\s+\"[^\"]*\")?\))")
HTML_SRC_RE = re.compile(r"(<img\b[^>]*?\bsrc=[\"'])([^\"']+)([\"'])", re.I)


def is_remote(path: str) -> bool:
    return bool(re.match(r"^(?:[a-z]+:)?//", path)) or path.startswith(("data:", "mailto:", "#", "/"))


def import_post(src: Path, slug: str | None, overwrite: bool, include_drafts: bool) -> None:
    src = src.expanduser().resolve()
    if not src.is_file():
        sys.exit(f"not a file: {src}")
    text = src.read_text(encoding="utf-8")
    meta, body = parse_front_matter(text)

    title = meta.get("title") or first_heading(body) or src.stem.replace("-", " ").replace("_", " ").title()
    slug = slug or meta.get("slug") or slugify(title)
    dest_dir = POSTS_DIR / slug
    if dest_dir.exists() and not overwrite:
        sys.exit(f"{dest_dir.relative_to(ROOT)} already exists (use --overwrite to replace it)")

    # Fill in any front matter the file is missing.
    if "title" not in meta:
        meta["title"] = title
    if "date" not in meta:
        meta["date"] = dt.date.today().isoformat()
    for k in ("summary", "tags"):
        meta.setdefault(k, "")

    dest_dir.mkdir(parents=True, exist_ok=True)
    copied: dict[str, str] = {}

    def relocate(ref: str) -> str:
        if is_remote(ref):
            return ref
        candidate = (src.parent / ref).resolve()
        if not candidate.is_file():
            print(f"  ! image not found, left as-is: {ref}")
            return ref
        if ref in copied:
            return copied[ref]
        name = candidate.name
        target = dest_dir / name
        n = 1
        while target.exists() and target.resolve() != candidate:
            target = dest_dir / f"{candidate.stem}-{n}{candidate.suffix}"
            n += 1
        shutil.copy2(candidate, target)
        copied[ref] = target.name
        print(f"  + {target.relative_to(ROOT)}")
        return target.name

    body = MD_IMAGE_RE.sub(lambda m: m.group(1) + relocate(m.group(2)) + m.group(3), body)
    body = HTML_SRC_RE.sub(lambda m: m.group(1) + relocate(m.group(2)) + m.group(3), body)

    fm_lines = ["---"] + [f"{k}: {v}" for k, v in meta.items()] + ["---", ""]
    (dest_dir / "index.md").write_text("\n".join(fm_lines) + body.lstrip("\n"), encoding="utf-8")
    print(f"  + {(dest_dir / 'index.md').relative_to(ROOT)}")
    print("Building…")
    build(include_drafts=include_drafts)


