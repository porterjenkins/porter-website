def copy_assets(post: Post, out_dir: Path) -> int:
    if not post.asset_dir:
        return 0
    n = 0
    for item in post.asset_dir.iterdir():
        if item.name.startswith(".") or item.suffix.lower() in ASSET_SKIP_SUFFIXES:
            continue
        target = out_dir / item.name
        if item.is_dir():
            shutil.copytree(item, target, dirs_exist_ok=True)
        else:
            shutil.copy2(item, target)
        n += 1
    return n


def is_generated_dir(d: Path) -> bool:
    page = d / "index.html"
    try:
        return GENERATED_MARK in page.read_text(encoding="utf-8")
    except OSError:
        return False


def update_home(posts: list[Post]) -> bool:
    if not HOME_HTML.exists():
        return False
    text = HOME_HTML.read_text(encoding="utf-8")
    start = text.find(HOME_START)
    end = text.find(HOME_END)
    if start == -1 or end == -1 or end < start:
        print(f"  ! {HOME_HTML.name}: markers {HOME_START} / {HOME_END} not found; skipped")
        return False
    start += len(HOME_START)
    new = text[:start] + "\n" + home_cards(posts) + "\n      " + text[end:]
    if new != text:
        HOME_HTML.write_text(new, encoding="utf-8")
        return True
    return False


def build(include_drafts: bool = False) -> list[Post]:
    sources = discover_posts()
    posts: list[Post] = []
    for src in sources:
        try:
            post = load_post(src)
        except Exception as e:  # noqa: BLE001
            print(f"  ! {src.relative_to(ROOT)}: {e}")
            continue
        if post.draft and not include_drafts:
            print(f"  - {post.slug} (draft, skipped)")
            continue
        posts.append(post)

    seen: dict[str, Path] = {}
    for p in posts:
        if p.slug in seen:
            sys.exit(f"duplicate slug {p.slug!r}: {seen[p.slug]} and {p.source}")
        seen[p.slug] = p.source

    posts.sort(key=lambda p: (p.date, p.slug), reverse=True)
    OUT_DIR.mkdir(exist_ok=True)

    for post in posts:
        render_post(post)
        out_dir = OUT_DIR / post.slug
        if out_dir.exists() and is_generated_dir(out_dir):
            shutil.rmtree(out_dir)
        out_dir.mkdir(parents=True, exist_ok=True)
        (out_dir / "index.html").write_text(post_page(post), encoding="utf-8")
        n_assets = copy_assets(post, out_dir)
        extras = f", {n_assets} asset(s)" if n_assets else ""
        math = ", math" if post.has_math else ""
        print(f"  ✓ {post.url}  ({post.reading_minutes} min{math}{extras})")

    # Remove generated pages whose source is gone.
    live = {p.slug for p in posts}
    for d in OUT_DIR.iterdir():
        if d.is_dir() and d.name not in live and is_generated_dir(d):
            shutil.rmtree(d)
            print(f"  - removed stale blog/{d.name}/")

    (OUT_DIR / "index.html").write_text(blog_index_page(posts), encoding="utf-8")
    print(f"  ✓ /blog/  ({len(posts)} post(s))")
    if update_home(posts):
        print(f"  ✓ {HOME_HTML.name} blog section updated")
    return posts


