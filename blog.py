# Posts
# ----------------------------------------------------------------------------

FRONT_MATTER_RE = re.compile(r"\A---[ \t]*\r?\n(.*?)\r?\n---[ \t]*\r?\n", re.S)
ASSET_SKIP_SUFFIXES = {".md", ".markdown"}


@dataclass
class Post:
    slug: str
    title: str
    date: dt.date
    summary: str
    tags: list[str]
    draft: bool
    body_md: str
    source: Path
    asset_dir: Path | None
    html: str = ""
    toc: str = ""
    has_math: bool = False
    reading_minutes: int = 1

    @property
    def url(self) -> str:
        return f"/blog/{self.slug}/"

    @property
    def date_iso(self) -> str:
        return self.date.isoformat()

    @property
    def date_human(self) -> str:
        return f"{self.date:%b} {self.date.day}, {self.date.year}"


def parse_front_matter(text: str) -> tuple[dict, str]:
    m = FRONT_MATTER_RE.match(text)
    if not m:
        return {}, text
    meta: dict[str, str] = {}
    for raw in m.group(1).splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if ":" not in line:
            raise ValueError(f"bad front matter line: {raw!r}")
        key, value = line.split(":", 1)
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        meta[key.strip().lower()] = value
    return meta, text[m.end():]


def slugify(text: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return s or "post"


def first_heading(md_text: str) -> str | None:
    m = re.search(r"^#\s+(.+?)\s*#*\s*$", md_text, re.M)
    return m.group(1).strip() if m else None


def load_post(path: Path) -> Post:
    text = path.read_text(encoding="utf-8")
    meta, body = parse_front_matter(text)

    if path.name.lower() == "index.md":
        slug = path.parent.name
        asset_dir = path.parent
    else:
        slug = path.stem
        asset_dir = None
    slug = meta.get("slug") or slug

    title = meta.get("title") or first_heading(body) or slug.replace("-", " ").title()
    # Drop a leading H1 that duplicates the title; the template renders it.
    body = re.sub(r"\A\s*#\s+" + re.escape(title) + r"\s*\n", "", body, count=1)

    date_str = meta.get("date")
    if date_str:
        date = dt.date.fromisoformat(date_str[:10])
    else:
        date = dt.date.fromtimestamp(path.stat().st_mtime)

    tags = [t.strip() for t in meta.get("tags", "").split(",") if t.strip()]
    draft = meta.get("draft", "").strip().lower() in {"true", "yes", "1"}

    return Post(
        slug=slug,
        title=title,
        date=date,
        summary=meta.get("summary", "").strip(),
        tags=tags,
        draft=draft,
        body_md=body,
        source=path,
        asset_dir=asset_dir,
    )


def discover_posts() -> list[Path]:
    if not POSTS_DIR.exists():
        return []
    found = []
    for p in sorted(POSTS_DIR.iterdir()):
        if p.is_dir() and (p / "index.md").exists():
            found.append(p / "index.md")
        elif p.is_file() and p.suffix.lower() in ASSET_SKIP_SUFFIXES:
            found.append(p)
    return found


def render_post(post: Post) -> None:
    md = make_markdown()
    post.html = md.convert(post.body_md)
    post.toc = getattr(md, "toc", "") or ""
    post.has_math = 'class="arithmatex"' in post.html
    words = len(re.findall(r"\w+", post.body_md))
    post.reading_minutes = max(1, round(words / WORDS_PER_MINUTE))


# ----------------------------------------------------------------------------
# Templating (deliberately tiny: {{name}} substitution)
# ----------------------------------------------------------------------------


def load_template(name: str) -> str:
    return (TEMPLATES_DIR / name).read_text(encoding="utf-8")


def fill(template: str, **values: str) -> str:
    def sub(m):
        key = m.group(1)
        if key not in values:
            raise KeyError(f"template placeholder {{{{{key}}}}} has no value")
        return values[key]

    return re.sub(r"\{\{(\w+)\}\}", sub, template)


def esc(s: str) -> str:
    return html.escape(s, quote=True)


def tags_html(tags: list[str]) -> str:
    return "".join(f'<span class="tag">{esc(t)}</span>' for t in tags)


KATEX_VERSION = "0.16.22"
KATEX_HEAD = f"""
  <link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/katex@{KATEX_VERSION}/dist/katex.min.css" />
  <script defer src="https://cdn.jsdelivr.net/npm/katex@{KATEX_VERSION}/dist/katex.min.js"></script>
  <script defer src="https://cdn.jsdelivr.net/npm/katex@{KATEX_VERSION}/dist/contrib/auto-render.min.js"
    onload="renderMathInElement(document.body, {{
      delimiters: [
        {{left: '\\\\[', right: '\\\\]', display: true}},
        {{left: '\\\\(', right: '\\\\)', display: false}}
      ],
      throwOnError: false
    }});"></script>
""".rstrip()


def post_page(post: Post) -> str:
    toc_block = ""
    if post.toc and post.toc.count("<li>") >= 3:
        toc_block = f'<nav class="toc" aria-label="Contents"><div class="toc-label">contents</div>{post.toc}</nav>'
    return fill(
        load_template("post.html"),
        generated=GENERATED_MARK,
        site_name=esc(SITE_NAME),
        title=esc(post.title),
        summary=esc(post.summary),
        canonical=SITE_URL + post.url,
        date_iso=post.date_iso,
        date_human=esc(post.date_human),
        reading=f"{post.reading_minutes} min read",
        tags=tags_html(post.tags),
        toc=toc_block,
        body=post.html,
        math_head=KATEX_HEAD if post.has_math else "",
        root="../../index.html",
        blog="../index.html",
        css="../blog.css",
    )


def listing_card(post: Post, base: str) -> str:
    """Card markup; `base` is the relative path to the blog/ directory from the page."""
    summary = f"<p>{esc(post.summary)}</p>" if post.summary else ""
    return f"""<a class="post-card" href="{base}{post.slug}/index.html">
  <div class="post-meta"><time datetime="{post.date_iso}">{esc(post.date_human)}</time><span>·</span><span>{post.reading_minutes} min read</span></div>
  <h3>{esc(post.title)}</h3>
  {summary}
  <div class="tags">{tags_html(post.tags)}</div>
</a>"""


def listing_row(post: Post) -> str:
    """One row of the blog index: date, title, summary."""
    summary = f"<p>{esc(post.summary)}</p>" if post.summary else ""
    return f"""<a class="post-row" href="{post.slug}/index.html">
  <time class="post-date" datetime="{post.date_iso}">{esc(post.date_human)}</time>
  <span class="post-row-body"><span class="post-title">{esc(post.title)}</span>{summary}</span>
  <span class="post-arrow" aria-hidden="true">→</span>
</a>"""


def blog_index_page(posts: list[Post]) -> str:
    cards = "\n".join(listing_row(p) for p in posts) or '<p class="empty">No posts yet.</p>'
    return fill(
        load_template("blog_index.html"),
        generated=GENERATED_MARK,
        site_name=esc(SITE_NAME),
        canonical=SITE_URL + "/blog/",
        count=str(len(posts)),
        cards=cards,
        root="../index.html",
        blog="index.html",
        css="blog.css",
    )


def home_cards(posts: list[Post]) -> str:
    cards = "\n".join(listing_card(p, "blog/") for p in posts[:HOME_CARD_COUNT])
    if not cards:
        cards = '<p class="empty">No posts yet.</p>'
    return f'<div class="post-grid">\n{cards}\n</div>'


