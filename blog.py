def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description="Build the blog for porterjenkins.com")
    sub = ap.add_subparsers(dest="cmd", required=True)

    b = sub.add_parser("build", help="render posts/ into blog/ and refresh the home page")
    b.add_argument("--drafts", action="store_true", help="include posts marked draft: true")

    i = sub.add_parser("import", help="copy a markdown file (and its local images) into posts/ and build")
    i.add_argument("path", type=Path, help="markdown file to import")
    i.add_argument("--slug", help="URL slug (default: from front matter or title)")
    i.add_argument("--overwrite", action="store_true", help="replace an existing post with the same slug")
    i.add_argument("--drafts", action="store_true", help="include drafts when rebuilding")

    sv = sub.add_parser("serve", help="build, then preview the site at http://127.0.0.1:8000/")
    sv.add_argument("--port", type=int, default=8000)
    sv.add_argument("--no-open", action="store_true", help="don't open a browser tab")
    sv.add_argument("--path", default="blog/", help="path to open (default: blog/)")
    sv.add_argument("--drafts", action="store_true", help="include drafts in the build")

    args = ap.parse_args(argv)
    if args.cmd == "serve":
        print("Building…")
        build(include_drafts=args.drafts)
        serve(args.port, not args.no_open, args.path)
    elif args.cmd == "build":
        print("Building…")
        build(include_drafts=args.drafts)
    elif args.cmd == "import":
        print(f"Importing {args.path}…")
        import_post(args.path, args.slug, args.overwrite, args.drafts)


if __name__ == "__main__":
    main()
